ALTER TABLE assignments
    ADD COLUMN IF NOT EXISTS grading_criteria JSONB,
    ADD COLUMN IF NOT EXISTS max_score NUMERIC(8,3) NOT NULL DEFAULT 10,
    ADD COLUMN IF NOT EXISTS auto_grade BOOLEAN NOT NULL DEFAULT FALSE;

ALTER TABLE assignment_submissions
    ADD COLUMN IF NOT EXISTS completed_at TIMESTAMP WITH TIME ZONE,
    ADD COLUMN IF NOT EXISTS score NUMERIC(8,3),
    ADD COLUMN IF NOT EXISTS max_score NUMERIC(8,3),
    ADD COLUMN IF NOT EXISTS feedback TEXT,
    ADD COLUMN IF NOT EXISTS grading_status VARCHAR(24) NOT NULL DEFAULT 'PENDING',
    ADD COLUMN IF NOT EXISTS graded_at TIMESTAMP WITH TIME ZONE,
    ADD COLUMN IF NOT EXISTS graded_by INTEGER REFERENCES users(id),
    ADD COLUMN IF NOT EXISTS retry_allowed BOOLEAN NOT NULL DEFAULT FALSE;

UPDATE assignment_submissions
SET completed_at = submitted_at
WHERE completed_at IS NULL;

CREATE TABLE IF NOT EXISTS student_action_logs (
    id UUID PRIMARY KEY,
    student_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    assignment_id UUID NOT NULL REFERENCES assignments(id) ON DELETE CASCADE,
    action VARCHAR(64) NOT NULL,
    payload JSONB,
    occurred_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_student_action_logs_student_occurred
    ON student_action_logs (student_id, occurred_at DESC);
